-- 电商后台管理系统 - 单链接数据表建表脚本
-- 抖店 / 京东 / 千牛   (日期 + ID 复合主键，全部 NOT NULL)

CREATE TABLE IF NOT EXISTS `抖店单链接数据表` (
  `店铺名` VARCHAR(255) NOT NULL,
  `统计周期` DATE NOT NULL,
  `商品名称` VARCHAR(255) NOT NULL,
  `商品编码` VARCHAR(64) NOT NULL,
  `载体` VARCHAR(64) NOT NULL,
  `品类` VARCHAR(128) NOT NULL,
  `自卖/合作` VARCHAR(64) NOT NULL,
  `成交金额` DECIMAL(18,2) NOT NULL,
  `结算金额` DECIMAL(18,2) NOT NULL,
  `用户支付金额` DECIMAL(18,2) NOT NULL,
  `成交订单数` INT NOT NULL,
  `成交人数` INT NOT NULL,
  `成交件数` INT NOT NULL,
  `成交客单价` DECIMAL(18,2) NOT NULL,
  `商品结算金额（结算时间）` DECIMAL(18,2) NOT NULL,
  `实际佣金支出` DECIMAL(18,2) NOT NULL,
  `净成交金额` DECIMAL(18,2) NOT NULL,
  `净成交订单数` INT NOT NULL,
  `成交退款金额` DECIMAL(18,2) NOT NULL,
  `退款金额(退款时间)` DECIMAL(18,2) NOT NULL,
  `退款订单数(退款时间)` INT NOT NULL,
  `退款人数(退款时间)` INT NOT NULL,
  `退款件数(退款时间)` INT NOT NULL,
  `商品曝光人数` INT NOT NULL,
  `商品曝光次数` INT NOT NULL,
  `商品点击人数` INT NOT NULL,
  `商品点击次数` INT NOT NULL,
  `曝光点击率（人数）` DECIMAL(10,4) NOT NULL,
  `投放消耗（店铺被投）` DECIMAL(18,2) NOT NULL,
  `投放消耗（推商品）` DECIMAL(18,2) NOT NULL,
  `投放贡献成交金额` DECIMAL(18,2) NOT NULL,
  `投放贡献成交退款金额` DECIMAL(18,2) NOT NULL,
  `投放费比（剔除退款、店铺被投）` DECIMAL(10,4) NOT NULL,
  `加购人数` INT NOT NULL,
  `收藏人数` INT NOT NULL,
  `评价好评率` DECIMAL(10,4) NOT NULL,
  `好评数` INT NOT NULL,
  `商品差评订单数` DECIMAL(18,2) NOT NULL,
  `商品差评率` DECIMAL(10,4) NOT NULL,
  `商品品质退货单量` DECIMAL(18,2) NOT NULL,
  `商品品质退货率` DECIMAL(10,4) NOT NULL,
  `投诉工单量` INT NOT NULL,
  `投诉率` DECIMAL(10,4) NOT NULL,
  `客服不满意会话量` DECIMAL(18,2) NOT NULL,
  `商详页曝光人数` INT NOT NULL,
  `商详页曝光点击率` DECIMAL(10,4) NOT NULL,
  `商详页成交转化率` DECIMAL(10,4) NOT NULL,
  `商详页跳失率` DECIMAL(10,4) NOT NULL,
  `平台消费券补贴金额` DECIMAL(18,2) NOT NULL,
  PRIMARY KEY (`统计周期`, `商品编码`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='抖店单链接数据表';

CREATE TABLE IF NOT EXISTS `京东单链接数据表` (
  `时间` DATE NOT NULL,
  `SPU` VARCHAR(64) NOT NULL,
  `SPU名称` VARCHAR(255) NOT NULL,
  `一级类目` VARCHAR(128) NOT NULL,
  `二级类目` VARCHAR(128) NOT NULL,
  `三级类目` VARCHAR(128) NOT NULL,
  `货号` VARCHAR(64) NOT NULL,
  `成交金额` DECIMAL(18,2) NOT NULL,
  `成交商品件数` INT NOT NULL,
  `成交单量` INT NOT NULL,
  `成交客户数` INT NOT NULL,
  `成交转化率` DECIMAL(10,4) NOT NULL,
  `客单价` DECIMAL(18,2) NOT NULL,
  `件单价` DECIMAL(18,2) NOT NULL,
  `UV价值` DECIMAL(18,2) NOT NULL,
  `搜索曝光次数` INT NOT NULL,
  `搜索点击次数` INT NOT NULL,
  `搜索点击率` DECIMAL(10,4) NOT NULL,
  `商品浏览量` INT NOT NULL,
  `商品访客数` INT NOT NULL,
  `商品人均浏览量` DECIMAL(10,4) NOT NULL,
  `商详平均停留时长` DECIMAL(18,2) NOT NULL,
  `商品曝光次数` INT NOT NULL,
  `商品曝光人数` INT NOT NULL,
  `加购商品件数` INT NOT NULL,
  `加购客户数` INT NOT NULL,
  `加购商品件数（正向）` INT NOT NULL,
  `加购商品件数（负向）` INT NOT NULL,
  `加购转化率` DECIMAL(10,4) NOT NULL,
  `加购金额` DECIMAL(18,2) NOT NULL,
  `下单金额` DECIMAL(18,2) NOT NULL,
  `下单商品件数` INT NOT NULL,
  `下单单量` INT NOT NULL,
  `下单客户数` INT NOT NULL,
  `下单转化率` DECIMAL(10,4) NOT NULL,
  `下单成交转化率` DECIMAL(10,4) NOT NULL,
  `取消及售后退款金额` DECIMAL(18,2) NOT NULL,
  `取消及售后退款商品件数` INT NOT NULL,
  `取消及售后退款单量` INT NOT NULL,
  PRIMARY KEY (`时间`, `SPU`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='京东单链接数据表';

