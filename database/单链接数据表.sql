  `商品加购件数` INT NOT NULL,
  `商品加购人数` INT NOT NULL,
  `下单买家数` INT NOT NULL,
  `下单件数` INT NOT NULL,
  `下单金额` DECIMAL(18,2) NOT NULL,
  `下单转化率` VARCHAR(32) NOT NULL,
  `支付买家数` INT NOT NULL,
  `支付件数` INT NOT NULL,
  `支付金额` DECIMAL(18,2) NOT NULL,
  `商品支付转化率` VARCHAR(32) NOT NULL,
  `支付新买家数` INT NOT NULL,
  `支付老买家数` INT NOT NULL,
  `老买家支付金额` DECIMAL(18,2) NOT NULL,
