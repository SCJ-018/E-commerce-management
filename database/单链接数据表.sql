  `结构化详情引导转化率` DECIMAL(10,4) NOT NULL,
  `结构化详情引导成交占比` DECIMAL(10,4) NOT NULL,
  PRIMARY KEY (`统计日期`, `商品ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='千牛单链接数据表';
